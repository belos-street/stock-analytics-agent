#!/usr/bin/env bun

/**
 * 报告结构性检查脚本（机械项）。
 * 用法: bun run .agents/business/report-review/scripts/check-report.ts <report.html|report.md>
 * 只查结构与一致性线索；数据正确性由 Agent 按 SKILL.md D1-D5 实证核验。
 *
 * 分流规则：
 * - .html → HTML 项（生成标记/引用锚点/figcaption/离线可开/图表 JS 线索）+ 公共项
 * - .md  → Markdown 项（表格数字线索）+ 公共项（免责声明/口径词）
 */

import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { basename, dirname, extname, join } from 'node:path'
import chalk from 'chalk'

const script = basename(import.meta.path)

/** 口径词分级：高危词一旦误用直接动摇结论（见 SKILL.md 陷阱库 #1） */
const SCOPE_KEYWORDS: Array<{ kw: string; high: boolean }> = [
  { kw: '年内', high: true },
  { kw: '今年', high: true },
  { kw: 'YTD', high: true },
  { kw: '近 1 年', high: false },
  { kw: '近 10 年', high: false },
  { kw: '分位', high: false }
]

function checkHtml(html: string, issues: string[], infos: string[]): void {
  // 1) 生成标记
  if (!html.trimStart().startsWith('<!-- Generated by Trae Work -->')) {
    issues.push('🟡 缺少首行 `<!-- Generated by Trae Work -->` 标记')
  }

  // 2) 引用锚点配对（容忍折行/空格/单引号等写法）
  const cited = new Set(
    [...html.matchAll(/href\s*=\s*["']?\s*#(cite-\d+)/gi)].map((m) => m[1])
  )
  const defined = new Set(
    [...html.matchAll(/id\s*=\s*["']?(cite-\d+)/gi)].map((m) => m[1])
  )
  for (const c of [...cited].filter((x) => !defined.has(x)).sort()) {
    issues.push(`🔴 正文引用 \`${c}\` 在页脚 Sources 无对应条目`)
  }
  for (const d of [...defined].filter((x) => !cited.has(x)).sort()) {
    issues.push(`🟡 页脚来源 \`${d}\` 未被正文引用`)
  }
  if (cited.size) {
    infos.push(`引用锚点: 正文 ${cited.size} 处 / 页脚 ${defined.size} 条`)
  }

  // 3) 图表容器与 figcaption
  const chartIds = [...html.matchAll(/class="chart-box"\s+id="([^"]+)"/g)].map(
    (m) => m[1]
  )
  const figures = [...html.matchAll(/<figure[^>]*>([\s\S]*?)<\/figure>/g)].map(
    (m) => m[1]
  )
  const figWithCaption = figures.filter((f) =>
    f.includes('<figcaption>')
  ).length
  if (figures.length !== figWithCaption) {
    issues.push(
      `🟡 ${figures.length - figWithCaption} 个图表缺少 <figcaption> 标题`
    )
  }
  if (chartIds.length) {
    infos.push(`图表容器 ${chartIds.length} 个: ${chartIds.join(', ')}`)
  }

  // 4) 外网依赖 / 绝对路径（离线可开约束，仅查资源类标签；页脚来源 <a href> 外链属正常）
  for (const tag of html.matchAll(/<(?:script|img|link|source)[^>]*>/g)) {
    for (const m of tag[0].matchAll(/(?:src|href)="([^"]+)"/g)) {
      const url = m[1]
      if (
        url.startsWith('http://') ||
        url.startsWith('https://') ||
        url.startsWith('//')
      ) {
        issues.push(`🟡 资源外链（离线不可开）: ${url}`)
      } else if (url.startsWith('/')) {
        issues.push(`🟡 资源绝对路径: ${url}`)
      }
    }
  }
}

function checkChartJs(file: string, infos: string[]): void {
  const assetsDir = join(dirname(file), 'assets')
  if (!existsSync(assetsDir)) return
  for (const name of readdirSync(assetsDir)
    .filter((n) => n.endsWith('.js'))
    .sort()) {
    const jsText = readFileSync(join(assetsDir, name), 'utf-8')
    for (const m of jsText.matchAll(
      /yAxis[^}]*?min:\s*([\d.]+)\s*,\s*max:\s*([\d.]+)/g
    )) {
      infos.push(`${name}: yAxis 范围 ${m[1]}–${m[2]}（核对是否截断关键价位）`)
    }
    const dataBlocks = [...jsText.matchAll(/data:\s*\[([\d.,\s]+)\]/g)].slice(
      0,
      6
    )
    for (const m of dataBlocks) {
      const nums = m[1]
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .slice(0, 12)
      if (nums.length) {
        infos.push(`${name}: 图表数据 [${nums.join(' ')}…]（与正文数字核对）`)
      }
    }
  }
}

function checkMarkdown(md: string, infos: string[]): void {
  // 表格数字线索（供 D3 复算核对）
  const rows = md.split('\n').filter((l) => /^\|.*\|$/.test(l.trim()))
  const numericCells = rows
    .flatMap((r) => r.split('|'))
    .filter((c) => /[\d]/.test(c) && /[¥%亿万倍元]/.test(c))
  if (rows.length) {
    infos.push(
      `Markdown 表格 ${rows.length} 行 / 含数字单元格 ${numericCells.length} 个（供 D3 复算核对）`
    )
  }
}

function checkCommon(text: string, issues: string[], d2: string[]): void {
  // 免责声明必备要素（纯文本匹配，md/html 通用）
  // md 报告常无「免责声明」标题、直接写免责句，此时在全文范围查关键词
  const disIdx = text.indexOf('免责声明')
  const scope = disIdx >= 0 ? text.slice(disIdx) : text
  for (const kw of ['不构成', '风险']) {
    if (!scope.includes(kw)) {
      issues.push(`🟡 免责声明缺少关键词: ${kw}`)
    }
  }

  // 口径词 → 独立 D2 必查清单（不混入 issues，避免稀释真问题）
  const body = text.replace(/<[^>]+>/g, ' ')
  for (const { kw, high } of SCOPE_KEYWORDS) {
    if (body.includes(kw)) {
      d2.push(
        high
          ? `⚠️ 高危「${kw}」——必须用 monthly K 线/对应窗口核验（陷阱库 #1 高发）`
          : `「${kw}」——按 D2 明确区间口径后核验`
      )
    }
  }
}

function main(): number {
  const file = process.argv[2]
  if (!file) {
    console.error(chalk.red(`用法: bun run ${script} <report.html|report.md>`))
    return 2
  }
  if (!existsSync(file)) {
    console.error(chalk.red(`❌ 文件不存在: ${file}`))
    return 2
  }

  const text = readFileSync(file, 'utf-8')
  const ext = extname(file).toLowerCase()
  const issues: string[] = []
  const infos: string[] = []
  const d2: string[] = []

  if (ext === '.html' || ext === '.htm') {
    checkHtml(text, issues, infos)
    checkChartJs(file, infos)
  } else if (ext === '.md') {
    checkMarkdown(text, infos)
    infos.push(
      'Markdown 报告：跳过 HTML 项（生成标记/引用锚点/figcaption/离线可开）'
    )
  } else {
    console.error(chalk.red(`❌ 不支持的扩展名 ${ext}（仅 .html / .md）`))
    return 2
  }
  checkCommon(text, issues, d2)

  console.log(chalk.bold(`=== 结构检查: ${basename(file)} ===`))
  for (const i of infos) console.log(`  ${chalk.cyan('ℹ️')}  ${i}`)
  if (issues.length) {
    console.log(`\n${chalk.yellow(`发现 ${issues.length} 个待核项:`)}`)
    for (const i of issues) console.log(`  ${i}`)
  } else {
    console.log(`\n${chalk.green('✅ 机械项全部通过')}`)
  }
  if (d2.length) {
    console.log(
      `\n${chalk.magenta.bold('🔍 D2 必查清单（口径词，逐项核验后方可交付）:')}`
    )
    for (const d of d2) console.log(`  ${d}`)
  }
  return 0
}

process.exit(main())
